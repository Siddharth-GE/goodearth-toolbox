import assert from "node:assert/strict";
import { test } from "node:test";

import { writeWorkbookBytes } from "@/lib/xlsx";
import { readReports, type DroppedFile } from "./upload";

const csv = (name: string, lines: string[]): DroppedFile => ({
  name,
  bytes: new TextEncoder().encode(lines.join("\n")),
});

const payments = (name: string, asOf: string, amount: string) =>
  csv(name, [
    `"Generated by Zoho on ${asOf}"`,
    "Payment Number,Date,Amount (BCY),Unused Amount (BCY)",
    `SAARANG-PR-1,01/10/2026,${amount},0`,
  ]);

test("each file is recognised, and the report date moves to the newest as-of date", () => {
  const out = readReports(
    [
      payments("Plot pay.csv", "Oct 21, 2026", "100"),
      csv("Villa sold.csv", [
        '"Generated by Zoho on Oct 20, 2026"',
        "Unit Name",
        "SAARANG-VILLA-01",
      ]),
    ],
    "2026-10-05",
  );
  assert.deepEqual(
    out.reports.map((r) => r.slot),
    ["plot_payments", "villa_sold"],
  );
  assert.deepEqual(out.errors, []);
  assert.equal(out.reportDate, "2026-10-21");
});

test("the report date never moves back, and an outstanding export never moves it", () => {
  const out = readReports(
    [
      payments("old.csv", "Oct 1, 2026", "1"),
      csv("Outstanding.csv", [
        '"Generated by Zoho on Dec 31, 2026"',
        "Status,Invoice#,Balance",
        "SAARANG-PLOT-01,,",
        "Overdue,INV-1,10",
      ]),
    ],
    "2026-10-05",
  );
  assert.equal(out.reports.length, 2);
  assert.equal(out.reportDate, "2026-10-05");
});

test("two files for one report: the later one counts, and the person is told", () => {
  const out = readReports(
    [payments("first.csv", "Oct 21, 2026", "1"), payments("second.csv", "Oct 21, 2026", "2")],
    null,
  );
  assert.equal(out.reports.length, 1);
  assert.equal(out.reports[0].meta.file, "second.csv");
  assert.deepEqual(out.errors, []);
  assert.match(out.notices[0], /first\.csv: replaced by second\.csv/);
});

test("an old .xls, an unreadable file and an unknown report are refused, the rest still read", () => {
  const out = readReports(
    [
      { name: "Villa Outstanding.xls", bytes: new Uint8Array([0xd0, 0xcf, 0x11, 0xe0, 0]) },
      { name: "broken.xlsx", bytes: new Uint8Array([1, 2, 3]) },
      csv("notes.csv", ["Hello", "world"]),
      payments("Plot pay.csv", "Oct 21, 2026", "1"),
    ],
    null,
  );
  assert.equal(out.reports.length, 1);
  assert.equal(out.errors.length, 3);
  assert.match(out.errors[0], /Export this report from Zoho as XLSX or CSV/);
  assert.match(out.errors[1], /broken\.xlsx: couldn't be read/);
  assert.match(out.errors[2], /doesn’t look like one of the eight Zoho reports/);
});

test("an .xlsx is read from its first sheet", () => {
  const bytes = writeWorkbookBytes([
    {
      name: "Report",
      rows: [
        ["Payment Number", "Date", "Amount (BCY)"],
        ["SAARANG-PR-9", 46300, 500],
      ],
    },
  ]);
  const out = readReports([{ name: "Plot.xlsx", bytes }], null);
  assert.deepEqual(out.errors, []);
  assert.deepEqual(out.reports[0].rows[0].slice(0, 2), ["SAARANG-PR-9", "2026-10-05"]);
});
