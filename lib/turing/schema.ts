/**
 * The tables and views Turing may read, with their columns, taken from the generated
 * database types. Pure: the generator script and the test that pins its output share it.
 */

export type Relation = { kind: "table" | "view"; columns: Record<string, string> };
export type Schema = Record<string, Relation>;

/** Reads `public`'s Tables and Views (their Row types) out of `supabase gen types` output. */
export function parseSchema(source: string): Schema {
  const schema: Schema = {};
  const lines = source.split(/\r?\n/);
  let kind: Relation["kind"] | null = null;
  let relation: string | null = null;
  let inRow = false;
  let column: string | null = null;

  for (const line of lines) {
    if (/^ {2}[a-z_]+: \{$/.test(line)) {
      // A schema block; only `public` is ours.
      kind = null;
      if (!line.startsWith("  public:")) relation = null;
      continue;
    }
    const section = /^ {4}(Tables|Views|Functions|Enums|CompositeTypes): /.exec(line);
    if (section) {
      kind = section[1] === "Tables" ? "table" : section[1] === "Views" ? "view" : null;
      relation = null;
      inRow = false;
      continue;
    }
    if (!kind) continue;
    const name = /^ {6}([a-z0-9_]+): \{$/.exec(line);
    if (name) {
      relation = name[1];
      schema[relation] = { kind, columns: {} };
      inRow = false;
      continue;
    }
    if (!relation) continue;
    if (/^ {8}Row: \{$/.test(line)) {
      inRow = true;
      continue;
    }
    if (/^ {8}\S/.test(line)) {
      inRow = false;
      continue;
    }
    if (!inRow) continue;
    const field = /^ {10}([a-z0-9_]+):\s*(.*)$/.exec(line);
    if (field) {
      column = field[1];
      schema[relation].columns[column] = field[2].trim();
      continue;
    }
    // A long union wraps onto deeper-indented lines.
    if (column && /^ {12,}\S/.test(line)) {
      const joined = `${schema[relation].columns[column]} ${line.trim()}`.trim();
      schema[relation].columns[column] = joined.replace(/^\| /, "");
    }
  }

  return schema;
}

/**
 * The generated module's text, sorted so a re-run with nothing changed writes the same bytes.
 * Turing's own tables are left out: a page any admin opens must never read one admin's chats.
 */
export function schemaModule(schema: Schema): string {
  const sorted = Object.fromEntries(
    Object.keys(schema)
      .filter((name) => !name.startsWith("turing_"))
      .sort()
      .map((name) => [
        name,
        {
          kind: schema[name].kind,
          columns: Object.fromEntries(
            Object.keys(schema[name].columns)
              .sort()
              .map((column) => [column, schema[name].columns[column]]),
          ),
        },
      ]),
  );
  return [
    "// Generated by scripts/turing-schema.ts from lib/supabase/database.types.ts — do not edit.",
    "// `npm run db:types` rewrites it; lib/turing/schema.test.ts fails when the two disagree.",
    'import type { Schema } from "./schema";',
    "",
    `export const TURING_SCHEMA: Schema = ${JSON.stringify(sorted, null, 2)};`,
    "",
  ].join("\n");
}
